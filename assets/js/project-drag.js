/* Hanging project rail. Load with defer after your existing app.js. */
(() => {
    function init() {
      document.querySelectorAll('.projects').forEach(rail => {
        if (rail.dataset.dragReady) return;
        rail.dataset.dragReady = 'true';
        rail.tabIndex = 0;
        rail.setAttribute('role', 'region');
        rail.setAttribute('aria-label', 'Projects. Drag left or right, or use arrow keys to browse.');
        const reduced = matchMedia('(prefers-reduced-motion: reduce)');
        let pointer = null, startX = 0, startY = 0, lastX = 0;
        let initialScroll = 0, dragging = false, blockClick = false;
        let angle = 0, velocity = 0, frame = 0, previousTime = 0;
  
        // A damped spring lets the clipped cards settle after each movement.
        function animate(time) {
          const dt = Math.min((time - (previousTime || time)) / 16.67, 2);
          previousTime = time;
          velocity += -angle * .075 * dt;
          velocity *= Math.pow(.83, dt);
          angle += velocity * dt;
          angle = Math.max(-9, Math.min(9, angle));
          rail.style.setProperty('--drag-sway', angle.toFixed(3) + 'deg');
          if (Math.abs(angle) + Math.abs(velocity) > .015) {
            frame = requestAnimationFrame(animate);
          } else {
            frame = 0;
            previousTime = 0;
            rail.style.setProperty('--drag-sway', '0deg');
          }
        }
        function sway(delta) {
          if (reduced.matches) return;
          velocity += Math.max(-2, Math.min(2, delta * .045));
          if (!frame) frame = requestAnimationFrame(animate);
        }
        rail.addEventListener('dragstart', event => event.preventDefault());
        rail.addEventListener('pointerdown', event => {
          if (!event.isPrimary || event.button !== 0) return;
          pointer = event.pointerId;
          startX = lastX = event.clientX;
          startY = event.clientY;
          initialScroll = rail.scrollLeft;
          dragging = false;
          blockClick = false;
        });
        rail.addEventListener('pointermove', event => {
          if (event.pointerId !== pointer) return;
          const dx = event.clientX - startX;
          if (!dragging) {
            if (Math.abs(event.clientY - startY) > Math.abs(dx) && Math.abs(event.clientY - startY) > 8) {
              pointer = null; // Leave vertical page scrolling to the browser.
              return;
            }
            if (Math.abs(dx) < 7) return;
            dragging = true;
            blockClick = true;
            rail.setPointerCapture(pointer);
            rail.classList.add('is-dragging');
          }
          event.preventDefault();
          rail.scrollLeft = initialScroll - dx;
          sway(event.clientX - lastX);
          lastX = event.clientX;
        });
        function end(event) {
          if (event.pointerId !== pointer) return;
          if (rail.hasPointerCapture(pointer)) rail.releasePointerCapture(pointer);
          pointer = null;
          dragging = false;
          rail.classList.remove('is-dragging');
          // Click follows pointerup; suppress only the click generated by this drag.
          setTimeout(() => { blockClick = false; }, 0);
        }
        window.addEventListener('pointerup', end);
        window.addEventListener('pointercancel', end);
        rail.addEventListener('lostpointercapture', end);
        rail.addEventListener('click', event => {
          if (blockClick && event.detail !== 0) {
            event.preventDefault();
            event.stopImmediatePropagation();
          }
        }, true);
        rail.addEventListener('keydown', event => {
          if (!['ArrowLeft', 'ArrowRight'].includes(event.key)) return;
          event.preventDefault();
          const direction = event.key === 'ArrowRight' ? 1 : -1;
          rail.scrollBy({ left: direction * rail.clientWidth * .75, behavior: reduced.matches ? 'instant' : 'smooth' });
          sway(direction * -24);
        });
      });
    }
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
    else init();
  })();
  